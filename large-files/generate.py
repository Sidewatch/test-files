def words(r: Rand, count: int) -> str:
    return " ".join(r.pick(WORDS) for _ in range(count))


def sentence(r: Rand, low: int, high: int) -> str:
    text = words(r, low + r.below(high - low + 1))
    return text[0].upper() + text[1:] + "."


def paragraph(r: Rand, sentences: int) -> str:
    return " ".join(sentence(r, 6, 14) for _ in range(sentences))


def ipv4(r: Rand) -> str:
    return f"{r.pick(['192.0.2', '198.51.100', '203.0.113'])}.{r.below(254) + 1}"


def ipv6(r: Rand) -> str:
    return f"2001:db8:{r.below(0xFFFF):x}::{r.below(0xFFFF) + 1:x}"


def iso(ms: int, millis: bool = True) -> str:
    stamp = time.strftime("%Y-%m-%dT%H:%M:%S", time.gmtime(ms // 1000))
    return f"{stamp}.{ms % 1000:03d}Z" if millis else stamp + "Z"


class Clock:
    """A timestamp that only moves forward, by a random step."""

    def __init__(self) -> None:
        self.ms = START_MS

    def tick(self, r: Rand, most_ms: int) -> int:
        self.ms += r.below(most_ms) + 1
        return self.ms


def fill(path: Path, limit: int, head: str, record, tail: str = "", joiner: str = "", max_lines: int | None = None):
    """Writes `head`, then record(0), record(1)… joined by `joiner`, then `tail`: as many records as keep the
    file within `limit` bytes (and `max_lines` line breaks). Returns (records, bytes, lines)."""
    head_b, tail_b, join_b = head.encode(), tail.encode(), joiner.encode()
    size = len(head_b) + len(tail_b)
    lines = head_b.count(b"\n") + tail_b.count(b"\n")
    count = 0
    with open(path, "wb") as out:
        out.write(head_b)
        while True:
            data = record(count).encode()
            add = len(data) + (len(join_b) if count else 0)
            add_lines = data.count(b"\n") + (join_b.count(b"\n") if count else 0)
            if size + add > limit or (max_lines is not None and lines + add_lines > max_lines):
                break
            if count:
                out.write(join_b)
            out.write(data)
            size += add
            lines += add_lines
            count += 1
        out.write(tail_b)
    return count, size, lines


# MARK: Logs

LEVELS = ["INFO"] * 14 + ["DEBUG"] * 3 + ["WARN"] * 2 + ["ERROR"]
FRAMES = ["Upstream.fetch (upstream.swift:212)", "Catalog.refresh (catalog.swift:88)", "Worker.run (worker.swift:41)",
          "Ledger.post (ledger.swift:310)", "Router.handle (router.swift:57)", "Queue.drain (queue.swift:133)"]


def log_record(r: Rand, clock: Clock, n: int, needle_every: int) -> str:
    """One log entry: a line, or an error line and its stack. Every `needle_every`-th carries `needle-NNNNN`."""
    ts = iso(clock.tick(r, 40))
    level = r.pick(LEVELS)
    service = r.pick(SERVICES)
    request = r.hex(12)
    needle = f"needle-{n // needle_every:05d}" if n % needle_every == needle_every - 1 else ""
    if r.below(10) == 0:
        entry = {"ts": ts, "level": level.lower(), "service": service, "req": request, "msg": sentence(r, 3, 8),
                 "region": r.pick(REGIONS), "latency_ms": r.below(50000) / 10}
        if needle:
            entry["trace"] = needle
        return json.dumps(entry, ensure_ascii=False, separators=(",", ":"))
    if level == "ERROR":
        message = (f"upstream failed host={service}-{r.below(100):02d}.{r.pick(DOMAINS)} "
                   f'error="connection reset by peer" retry_in={r.below(30) + 1}s')
    elif level == "WARN":
        message = r.pick([
            f"rate limited client={ipv4(r)} bucket={r.pick(WORDS)} remaining=0 reset_in={r.below(60) + 1}s",
            f"slow query took={r.below(4000) + 500}ms "
            f'sql="SELECT id, title FROM items WHERE category_id = {r.below(500)} ORDER BY updated_at DESC LIMIT 50"',
            f"retrying job={r.pick(WORDS)}-sync attempt={r.below(5) + 2} backoff_ms={r.below(5000)}",
        ])
    else:
        message = r.pick([
            f"request completed method={r.pick(['GET', 'GET', 'GET', 'POST', 'PUT', 'DELETE'])} "
            f"path=/v2/{r.pick(WORDS)}s/{r.below(100000)} status={r.pick([200, 200, 200, 201, 204, 304, 404])} "
            f"bytes={r.below(90000)} duration_ms={r.below(20000) / 10} client={ipv4(r)} "
            f'ua="ExampleClient/3.{r.below(20)} (macOS 26.{r.below(4)})"',
            f"cache miss key={r.pick(WORDS)}:{r.below(100000)} region={r.pick(REGIONS)} fallback=origin",
            f"signed in user=user-{r.below(100000):05d} method={r.pick(['password', 'passkey', 'sso'])} ip={ipv6(r)}",
            f"job {r.pick(['started', 'finished', 'queued'])} name={r.pick(WORDS)}-sync items={r.below(10000)}",
            f'customer note="{r.pick(PLACES)}: {sentence(r, 4, 10)}"',
        ])
    line = f"{ts} {level:<5} [{service}] req={request} {message}" + (f" trace={needle}" if needle else "")
    if level == "ERROR" and r.chance(40):
        frames = [f"    at Example.{r.pick(FRAMES)}" for _ in range(3 + r.below(5))]
        line += "\n" + "\n".join(frames)
    return line


def write_log(path: Path, limit: int, seed: int, needle_every: int):
    r, clock = Rand(seed), Clock()
    return fill(path, limit, "", lambda n: log_record(r, clock, n, needle_every), "\n", "\n")


def write_long_line_log(path: Path, seed: int):
    """An ordinary log with one line of 1.5 MiB in its middle: a base64 payload logged whole."""
    r, clock = Rand(seed), Clock()
    before = "\n".join(log_record(r, clock, n, 10**9) for n in range(2000))
    payload = base64.b64encode(r.bytes(LARGE_FILE_VIEW_LINE * 3 // 2 * 3 // 4)).decode()
    long_line = f"{iso(clock.tick(r, 40))} INFO  [upload] req={r.hex(12)} stored blob payload={payload}"
    after = "\n".join(log_record(r, clock, n, 10**9) for n in range(2000))
    text = f"{before}\n{long_line}\n{after}\n"
    path.write_bytes(text.encode())
    return 4001, len(text.encode()), text.count("\n")


