SQL_SCHEMA = f"""-- {HEADER}
-- A shop's schema and data, SQLite dialect: constraints, an index, a view, a trigger, multi-row inserts.
PRAGMA foreign_keys = ON;
BEGIN TRANSACTION;

CREATE TABLE customers (
  id INTEGER PRIMARY KEY,
  handle TEXT NOT NULL UNIQUE,
  email TEXT NOT NULL,
  country TEXT CHECK (length(country) = 2),
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE products (
  id INTEGER PRIMARY KEY,
  sku TEXT NOT NULL UNIQUE,
  title TEXT NOT NULL,
  price_cents INTEGER NOT NULL CHECK (price_cents >= 0),
  notes TEXT
);

CREATE TABLE orders (
  id INTEGER PRIMARY KEY,
  customer_id INTEGER NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  placed_at TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  updated_at TEXT
);

CREATE TABLE order_items (
  order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES products(id),
  quantity INTEGER NOT NULL DEFAULT 1,
  PRIMARY KEY (order_id, product_id)
);

CREATE INDEX idx_orders_customer ON orders(customer_id);

/* What each order comes to. */
CREATE VIEW order_totals AS
  SELECT o.id AS order_id, SUM(p.price_cents * i.quantity) AS total_cents
  FROM orders o JOIN order_items i ON i.order_id = o.id JOIN products p ON p.id = i.product_id
  GROUP BY o.id;

CREATE TRIGGER orders_touch AFTER UPDATE OF status ON orders
BEGIN
  UPDATE orders SET updated_at = CURRENT_TIMESTAMP WHERE id = NEW.id;
END;
"""


def sql_round(r: Rand, n: int) -> str:
    """Fifty customers, products and orders, and their order lines: every reference to a row already in."""
    base = n * 50

    def text(value: str) -> str:
        return "'" + value.replace("'", "''") + "'"

    def handle(k: int) -> str:
        return f"o'neill-{base + k:06d}" if k % 7 == 0 else f"user-{base + k:06d}"

    customers = ",\n".join(
        f"  ({base + k}, {text(handle(k))}, 'user-{base + k:06d}@example.com', '{r.pick(COUNTRIES)}')"
        for k in range(1, 51))
    products = ",\n".join(
        f"  ({base + k}, 'SKU-{base + k:06d}', {text(words(r, 3).title())}, {r.below(100000)}, "
        f"{'NULL' if r.chance(50) else text(r.pick(['a; semicolon inside a string', sentence(r, 3, 7), r.pick(PLACES)]))})"
        for k in range(1, 51))
    orders = ",\n".join(
        f"  ({base + k}, {1 + r.below(base + 50)}, '{iso(START_MS + r.below(86_400_000 * 30), millis=False)}', "
        f"'{r.pick(['pending', 'paid', 'shipped'])}', NULL)" for k in range(1, 51))
    lines = ",\n".join(
        f"  ({base + k}, {1 + r.below(base + 50)}, {1 + r.below(4)})" for k in range(1, 51))
    return (f"\n-- Round {n:05d}\nINSERT INTO customers (id, handle, email, country) VALUES\n{customers};\n"
            f"INSERT INTO products (id, sku, title, price_cents, notes) VALUES\n{products};\n"
            f"INSERT INTO orders (id, customer_id, placed_at, status, updated_at) VALUES\n{orders};\n"
            f"INSERT INTO order_items (order_id, product_id, quantity) VALUES\n{lines};\n")


def write_sql(path: Path, limit: int, seed: int):
    r = Rand(seed)
    return fill(path, limit, SQL_SCHEMA, lambda n: sql_round(r, n), "\nCOMMIT;\n")


def png(width: int, height: int, tint: int) -> bytes:
    """A small gradient PNG, made here so the notebook carries a real image."""
    rows = b"".join(
        b"\x00" + b"".join(bytes(((x * 255) // width, (y * 255) // height, (tint * 37) % 256)) for x in range(width))
        for y in range(height))

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b"")


