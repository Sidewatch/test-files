class Rand:
    """SplitMix64: the same stream on every Python and every platform."""

    def __init__(self, seed: int) -> None:
        self.state = seed & MASK

    def next(self) -> int:
        self.state = (self.state + 0x9E3779B97F4A7C15) & MASK
        z = self.state
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK
        return z ^ (z >> 31)

    def below(self, n: int) -> int:
        return self.next() % n

    def pick(self, items):
        return items[self.next() % len(items)]

    def chance(self, percent: int) -> bool:
        return self.next() % 100 < percent

    def hex(self, digits: int) -> str:
        out = ""
        while len(out) < digits:
            out += f"{self.next():016x}"
        return out[:digits]

    def real(self, low: float, high: float, places: int) -> float:
        return round(low + (high - low) * (self.next() / 2**64), places)

    def bytes(self, count: int) -> bytes:
        return b"".join(self.next().to_bytes(8, "little") for _ in range((count + 7) // 8))[:count]


