def catalog_item(r: Rand, n: int, long_text: bool = False) -> dict:
    description = paragraph(r, 10 + r.below(10)) if long_text else sentence(r, 6, 16)
    if r.chance(20):
        description += f'\nSecond line with "quotes", a tab\there and {r.pick(PLACES)}.'
    return {
        "id": f"item-{n:06d}",
        "sku": f"SKU-{r.below(90000) + 10000}-{r.pick('ABCDEFGH')}",
        "title": words(r, 3).title(),
        "price": {"amount": r.below(100000) / 100, "currency": r.pick(CURRENCIES)},
        "inStock": r.chance(70),
        "rating": None if r.chance(15) else round(1 + r.below(41) / 10, 1),
        "tags": [r.pick(WORDS) for _ in range(r.below(5))],
        "dimensions": {"w": r.real(1, 200, 1), "h": r.real(1, 200, 1), "d": r.real(0.1, 50, 2), "unit": "cm"},
        "variants": [{"id": f"v{k}", "color": r.pick(COLORS), "size": r.pick(SIZES), "stock": r.below(200)}
                     for k in range(r.below(4))],
        "description": description,
        "origin": {"city": r.pick(PLACES), "country": r.pick(COUNTRIES)},
        "updatedAt": iso(START_MS + r.below(86_400_000 * 30), millis=False),
        "related": [f"item-{r.below(n + 1):06d}" for _ in range(r.below(3))],
    }


def indented(text: str, spaces: int) -> str:
    pad = " " * spaces
    return "\n".join(pad + line for line in text.split("\n"))


