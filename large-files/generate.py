EVENT_TYPES = ["page_view", "search", "add_to_cart", "purchase", "signup", "error"]


def write_events_jsonl(path: Path, limit: int, seed: int):
    r, clock = Rand(seed), Clock()

    def event(n: int) -> str:
        kind = r.pick(EVENT_TYPES)
        props: dict = {"page": f"/{r.pick(WORDS)}/{r.below(1000)}"}
        if kind == "search":
            props = {"query": words(r, 1 + r.below(3)), "results": r.below(500), "filters": {"inStock": r.chance(50)}}
        elif kind in ("add_to_cart", "purchase"):
            props = {"items": [{"id": f"item-{r.below(100000):06d}", "qty": 1 + r.below(4)} for _ in range(1 + r.below(3))],
                     "total": {"amount": r.below(50000) / 100, "currency": r.pick(CURRENCIES)}}
        elif kind == "error":
            props = {"code": r.pick(["E_TIMEOUT", "E_NETWORK", "E_VALIDATION"]), "message": sentence(r, 4, 9),
                     "stack": [r.pick(FRAMES) for _ in range(2)]}
        return json.dumps({
            "id": f"evt-{n:08d}", "ts": iso(clock.tick(r, 900)), "type": kind,
            "user": {"id": f"user-{r.below(100000):05d}", "country": r.pick(COUNTRIES), "beta": r.chance(10)},
            "context": {"app": f"3.{r.below(20)}.{r.below(10)}", "os": f"macOS 26.{r.below(4)}", "ip": ipv4(r),
                        "locale": r.pick(["en-GB", "fr-FR", "de-CH", "ja-JP", "pt-BR"])},
            "props": props,
        }, ensure_ascii=False, separators=(",", ":"))

    return fill(path, limit, "", event, "\n", "\n")


def write_geojson(path: Path, limit: int, seed: int):
    r = Rand(seed)

    def point() -> list:
        return [r.real(-180, 180, 6), r.real(-85, 85, 6)]

    def ring() -> list:
        lon, lat = r.real(-170, 170, 4), r.real(-80, 80, 4)
        points = [[round(lon + r.real(-2, 2, 6), 6), round(lat + r.real(-2, 2, 6), 6)] for _ in range(4 + r.below(12))]
        return points + [points[0]]

    def feature(n: int) -> str:
        kind = r.pick(["Point", "Point", "LineString", "Polygon", "MultiPolygon"])
        if kind == "Point":
            coordinates = point()
        elif kind == "LineString":
            coordinates = [point() for _ in range(2 + r.below(20))]
        elif kind == "Polygon":
            coordinates = [ring()]
        else:
            coordinates = [[ring()] for _ in range(2 + r.below(3))]
        return json.dumps({
            "type": "Feature", "id": n,
            "geometry": {"type": kind, "coordinates": coordinates},
            "properties": {"name": f"{r.pick(PLACES)} {words(r, 1)}", "population": r.below(5_000_000),
                           "tags": [r.pick(WORDS) for _ in range(r.below(4))], "active": r.chance(80)},
        }, ensure_ascii=False, separators=(", ", ": "))

    return fill(path, limit, '{"type": "FeatureCollection", "features": [\n', feature, "\n]}\n", ",\n")


