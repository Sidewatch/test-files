def write_all(root: Path, entries) -> None:
    for name, write in entries:
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        started = time.time()
        records, size, lines = write(path)
        needles = path.read_bytes().count(b"needle-") if name.endswith(".log") and size < 128 * MIB else 0
        extra = f", {needles} needles" if needles else ""
        print(f"{name:34} {size:>12,} bytes {lines:>10,} lines {records:>9,} records{extra}"
              f"  ({time.time() - started:.1f} s)")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--verify", action="store_true", help="regenerate into a temporary folder and compare")
    parser.add_argument("--huge", metavar="DIR", help="also write the 100 MiB and 1 GiB files into DIR")
    args = parser.parse_args()
    here = Path(__file__).resolve().parent
    if args.verify:
        with tempfile.TemporaryDirectory() as scratch:
            write_all(Path(scratch), files())
            differ = [name for name, _ in files()
                      if not (here / name).exists() or sha256(here / name) != sha256(Path(scratch) / name)]
        for name in differ:
            print(f"differs: {name}")
        print("every file matches its generator" if not differ else f"{len(differ)} file(s) differ: regenerate them")
        return 1 if differ else 0
    write_all(here, files())
    if args.huge:
        out = Path(args.huge).expanduser().resolve()
        if out == here.parent or here.parent in out.parents:
            print("--huge writes outside this repository: GitHub refuses files over 100 MiB", file=sys.stderr)
            return 2
        out.mkdir(parents=True, exist_ok=True)
        write_all(out, huge_files())
    return 0


if __name__ == "__main__":
    sys.exit(main())
